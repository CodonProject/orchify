from dataclasses import dataclass, field
from typing import Optional, AsyncGenerator, Literal, Callable, Dict, Any
from functools import partial


@dataclass
class Chunk:
    '''One chunk of a streamed LLM response.

    Attributes:
        is_cot (bool): True while the model is emitting reasoning
            ("chain of thought") rather than answer content.
        content (str): Answer text carried by this chunk.
        is_assembly_tool (bool): True when the chunk is a fragment of a tool
            call whose arguments are assembled from the stream.
        assembly_chunk (str): The raw fragment, when ``is_assembly_tool``.
        total_content (str): Answer text accumulated so far.
        total_cot_content (str): Reasoning text accumulated so far.
        total_tool_call (list[dict]): Tool calls accumulated so far.
        is_cot_end (bool): True when this chunk closes the reasoning block.
    '''

    is_cot: bool
    content: str

    is_assembly_tool: bool = field(default=False)
    assembly_chunk: str    = field(default='')

    total_content: str          = field(default='')
    total_cot_content: str      = field(default='')
    total_tool_call: list[dict] = field(default_factory=list)

    is_cot_end: bool = field(default=False)


@dataclass
class FinalStatus:
    '''Final status of one completed LLM request.

    Attributes:
        content (str): The complete answer text.
        reasoning (str): The complete reasoning text, when the model exposed it.
        tool_calls (list[dict]): Tool calls requested by the model.
        completion_tokens (int): Tokens generated by the model.
        prompt_tokens (int): Tokens in the prompt.
        prompt_cache_hit_tokens (int): Prompt tokens served from a provider cache.
        prompt_cache_miss_tokens (int): Prompt tokens that missed the cache.
        total_tokens (int): Total tokens billed for the request.
    '''

    content: str
    reasoning: str
    tool_calls: list[dict] = field(default_factory=list)

    completion_tokens: int = field(default=0)
    prompt_tokens: int = field(default=0)
    prompt_cache_hit_tokens: int = field(default=0)
    prompt_cache_miss_tokens: int = field(default=0)
    total_tokens: int = field(default=0)


@dataclass
class Response:
    '''One item of an LLM response stream.

    Attributes:
        current_chunk (Optional[Chunk]): The chunk just received, when any.
        final_status (Optional[FinalStatus]): Set on the last item.
        is_final (bool): True for the last item of the stream.
    '''

    current_chunk: Optional[Chunk]
    final_status: Optional[FinalStatus] = field(default=None)

    is_final: bool = field(default=False)


NextRequest = Callable[..., AsyncGenerator['Response', None]]


def scope_matches(scope, agent_name) -> bool:
    '''Check whether a plugin scope matches an agent name.

    Acceptable forms for ``scope`` (or a list of them):

    * None or ``'*'``: matches anything (global).
    * ``'agent'``: matches any named agent.
    * ``'agent:foo'``: matches the agent named ``foo``.
    * callable: called with the agent name; a truthy result matches.

    Args:
        scope (Any): The scope to test, or a list of scopes.
        agent_name (str): Name of the agent making the request.

    Returns:
        bool: True when the scope matches.
    '''
    if scope is None or scope == '*':
        return True
    items = scope if isinstance(scope, (list, tuple, set)) else [scope]
    agent_name = agent_name or ''
    for item in items:
        if callable(item):
            try:
                if item(agent_name):
                    return True
            except Exception:
                pass
            continue
        if item in ('*', 'agent'):
            return True
        if item == f'agent:{agent_name}':
            return True
    return False


class Middleware:
    '''Base class for LLM request middleware (onion model).

    Implement ``__call__`` as an async generator. Before starting the underlying
    stream you may mutate ``kwargs`` (messages, model, tools, temperature, top_p,
    json_format, max_tokens, thinking, effort, extra_data, scope). The returned
    async generator wraps the Response stream, which allows observing or
    transforming every Response (or the final status) and handling errors and
    retries around the stream::

        class MyMiddleware(Middleware):
            async def __call__(self, kwargs, next_request):
                kwargs['thinking'] = 'disabled'
                try:
                    async for resp in next_request(kwargs):
                        yield resp
                except httpx.HTTPStatusError:
                    ...retry...

    The first registered middleware is the outermost. ``scope`` (None or ``'*'``
    for global) restricts the middleware to requests whose scope matches (see
    ``scope_matches``), usually the agent name.

    Attributes:
        name (str): Middleware name; defaults to the class name.
        scope (Any): Scope filter applied by ``matches``.
    '''

    name: str = ''
    scope: Any = None

    def __init__(self, name: str = '', scope=None):
        '''Create a middleware.

        Args:
            name (str): Label used in logs and in the middleware listing;
                defaults to the class name.
            scope (Optional[Union[str, Sequence[str]]]): Agent or group names this
                middleware applies to, matched with ``scope_matches``; None means
                every agent.
        '''
        self.name = name or self.__class__.__name__
        self.scope = scope

    def matches(self, agent_name) -> bool:
        '''Check whether this middleware applies to an agent.

        Args:
            agent_name (str): Name of the agent making the request.

        Returns:
            bool: True when the middleware's scope matches.
        '''
        return scope_matches(self.scope, agent_name)

    async def __call__(self, kwargs: Dict[str, Any], next_request: NextRequest) -> AsyncGenerator[Response, None]:
        '''Wrap ``next_request`` with this middleware.

        Args:
            kwargs (Dict[str, Any]): Request kwargs; mutate them to change the
                outgoing request.
            next_request (NextRequest): Callable returning the inner Response stream.

        Yields:
            Response: The response items produced by the inner stream.
        '''
        raise NotImplementedError('Middleware subclasses must implement __call__.')


class _FuncMiddleware(Middleware):
    '''Wraps a plain async-callable (async generator of Response) as a Middleware.'''

    def __init__(self, func: NextRequest):
        super().__init__(name=getattr(func, '__name__', 'middleware'))
        self._func = func

    async def __call__(self, kwargs: Dict[str, Any], next_request: NextRequest) -> AsyncGenerator[Response, None]:
        async for resp in self._func(kwargs, next_request):
            yield resp


class LLMInterface:
    '''Streaming LLM backend shared by every Agent.

    Subclasses implement ``_core_request`` as an async generator of
    :class:`Response`. Middlewares registered with ``use`` wrap the stream in
    registration order (the first one is outermost), and plain ``(kwargs,
    next_request)`` callables are accepted as well.

    Attributes:
        middlewares (list[Middleware]): Registered middleware, outermost first.
    '''

    def __init__(self):
        self.middlewares: list['Middleware'] = []

    def use(self, middleware, scope=None):
        '''Register one middleware or a list of them.

        Middleware instances and plain ``(kwargs, next_request)`` callables are both
        accepted; callables are wrapped automatically. The first registered
        middleware is the outermost.

        Args:
            middleware (Union[Middleware, Callable, List, Tuple]): Middleware to
                register.
            scope (Any): Optional scope assigned to the middleware (see
                ``Middleware.scope``).

        Returns:
            Any: The input, so ``use`` also works as a decorator.
        '''
        items = middleware if isinstance(middleware, (list, tuple)) else [middleware]
        for mw in items:
            if isinstance(mw, Middleware):
                pass
            elif callable(mw):
                mw = _FuncMiddleware(mw)
            else:
                raise TypeError(f'Middleware must be a Middleware instance or callable, got {type(mw)}')
            if scope is not None:
                mw.scope = scope
            self.middlewares.append(mw)
        return middleware

    def _dispatch(self, kwargs: Dict[str, Any], scope: str = '*') -> AsyncGenerator[Response, None]:
        enabled_plugins = kwargs.pop('_enabled_plugins', None)

        def core_dispatch(k: Dict[str, Any]) -> AsyncGenerator[Response, None]:
            k = {kk: vv for kk, vv in k.items() if kk != 'scope'}
            return self._core_request(**k)

        chain: Callable = core_dispatch
        for mw in reversed(self.middlewares):
            if mw.matches(scope):
                if enabled_plugins is not None and hasattr(mw, 'owner') and mw.owner and mw.owner not in enabled_plugins:
                    continue
                chain = partial(mw, next_request=chain)
        return chain(kwargs)

    async def _core_request(self, **kwargs: Any) -> AsyncGenerator[Response, None]:
        raise NotImplementedError('Subclasses must implement _core_request.')

    async def request(
        self,
        messages: list[dict],
        model: str = 'gpt-4o',
        tools: Optional[list[dict]] = None,
        temperature: float = 0.7,
        top_p: float = 1.0,
        json_format: bool = False,
        max_tokens: Optional[int] = None,
        thinking: Literal['disabled', 'enabled', 'auto'] = 'auto',
        effort: Literal['minimal', 'low', 'medium', 'high', 'xhigh'] = 'medium',
        extra_data: Optional[dict] = None,
        scope: str = '*',
        _enabled_plugins=None,
    ) -> AsyncGenerator[Response, None]:
        '''Stream a chat completion request.

        Args:
            messages (List[dict]): Conversation messages, in OpenAI format.
            model (Optional[str]): Model id; defaults to the interface's model.
            tools (Optional[list]): Tool schemas available to the model.
            temperature (Optional[float]): Sampling temperature.
            top_p (Optional[float]): Nucleus sampling probability.
            json_format (Optional[bool]): Request a JSON-only response.
            max_tokens (Optional[int]): Output token limit.
            thinking (Optional[str]): Reasoning mode hint, e.g. ``'auto'``.
            effort (Optional[str]): Reasoning effort hint.
            extra_data (Optional[dict]): Provider-specific extra fields.
            scope (Optional[str]): Request scope used for middleware filtering,
                usually the agent name.
            _enabled_plugins (Optional[Set[str]]): Plugin ids allowed to act on this
                request.

        Yields:
            Response: Streamed response items, the last one with ``is_final`` set.
        '''
        kwargs: Dict[str, Any] = {
            'messages': messages,
            'model': model,
            'tools': tools,
            'temperature': temperature,
            'top_p': top_p,
            'json_format': json_format,
            'max_tokens': max_tokens,
            'thinking': thinking,
            'effort': effort,
            'extra_data': extra_data,
            'scope': scope,
            '_enabled_plugins': _enabled_plugins,
        }
        async for resp in self._dispatch(kwargs, scope=scope):
            yield resp
